"""Command-line entry point: `python -m app.cli --help`."""
import argparse


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="stylistic-text-generator-comparator", description="Sports journalists use this to compare text generated by a LoRA-adapted LLM with an N-gram model, both fine-tuned on specific sports commentary styles.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")

    # Milestone 1
    sub.add_parser("corpus", help="Prepare and display the sports commentary corpus")

    # Milestone 2
    p_ngram = sub.add_parser("ngram", help="Generate text with the N-gram model")
    p_ngram.add_argument("--prompt", default="The striker", help="Generation prompt")
    p_ngram.add_argument("--tokens", type=int, default=30, help="Max tokens to generate")
    p_ngram.add_argument("--n", type=int, default=3, help="N-gram order")

    # Milestone 5
    p_gen = sub.add_parser("generate", help="Generate text with the LoRA-adapted LLM")
    p_gen.add_argument("--prompt", default="What an absolute thunderbolt", help="Generation prompt")
    p_gen.add_argument("--tokens", type=int, default=30, help="Max tokens to generate")
    p_gen.add_argument("--temperature", type=float, default=0.8, help="Sampling temperature")
    p_gen.add_argument("--epochs", type=int, default=10, help="Training epochs for LoRA")

    # Milestone 6
    p_cmp = sub.add_parser("compare", help="Side-by-side comparison of N-gram vs LoRA LLM")
    p_cmp.add_argument("--prompt", default="The striker picks up the ball", help="Prompt for both models")
    p_cmp.add_argument("--tokens", type=int, default=25, help="Max tokens to generate")
    p_cmp.add_argument("--temperature", type=float, default=0.8, help="Sampling temperature")
    p_cmp.add_argument("--epochs", type=int, default=10, help="Training epochs for LoRA")

    args = parser.parse_args(argv)

    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")

    elif args.command == "corpus":
        from app.core import milestone_1
        res = milestone_1()
        print(f"Corpus prepared: {res['num_sentences']} sentences, {res['num_tokens']} tokens")
        print(f"Vocabulary size: {res['vocab_size']}")
        print(f"Sample sentence: {' '.join(res['sentences'][0])}")

    elif args.command == "ngram":
        from app.core import milestone_1, milestone_2
        corpus_dict = milestone_1()
        res = milestone_2(corpus_dict=corpus_dict, n=args.n, prompt=args.prompt, max_tokens=args.tokens)
        print(f"\n[N-gram (n={args.n})] Prompt: \"{args.prompt}\"")
        print(f"Generated: {res['generated_text']}")

    elif args.command == "generate":
        from app.core import milestone_1, milestone_4, milestone_5
        corpus_dict = milestone_1()
        print(f"Training LoRA adapter for {args.epochs} epochs...")
        lora_dict = milestone_4(corpus_dict=corpus_dict, epochs=args.epochs)
        res = milestone_5(lora_trained_dict=lora_dict, prompt=args.prompt, max_new_tokens=args.tokens, temperature=args.temperature)
        print(f"\n[LoRA LLM] Prompt: \"{args.prompt}\"")
        print(f"Generated: {res['generated_text']}")

    elif args.command == "compare":
        from app.core import milestone_6
        print(f"Running full pipeline and training LoRA for {args.epochs} epochs…")
        res = milestone_6(prompt=args.prompt, max_tokens=args.tokens, temperature=args.temperature, print_report=True)


if __name__ == "__main__":
    main()
